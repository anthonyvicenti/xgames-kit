export const RULES_MARKS = ['<!-- gf:rules:start (generated by scripts/sync-skills.mjs from builder/loop/brief.mjs RULES; never edit between the marks) -->', '<!-- gf:rules:end -->'];
/** AGENTS.md with its rules block as builder/loop/brief.mjs RULES gives it. */
async function agentsWithRules(root) {
  const md = await readFile(path.join(root, 'AGENTS.md'), 'utf8');
  const a = md.indexOf(RULES_MARKS[0].slice(0, 20)), b = md.indexOf(RULES_MARKS[1]);
  if (a < 0 || b < a) throw new Error('gen-loop: AGENTS.md has no rules block (gf:rules:start … gf:rules:end)');
  const block = [RULES_MARKS[0], ...RULES.map((r, i) => `${i + 1}. ${r}`), RULES_MARKS[1]].join('\n');
  return md.slice(0, a) + block + md.slice(b + RULES_MARKS[1].length);
}

/** Every generated file. → [{ file (relative to the kit root), text }] */
export async function generatedFiles(root = ROOT) {
  return [
    { file: 'skills/build-loop/SKILL.md', text: buildLoopSkill() },
    { file: 'plugin/agents/playtester.md', text: playtesterAgent() },
    { file: 'plugin/agents/reader.md', text: readerAgent() },
    { file: 'AGENTS.md', text: await agentsWithRules(root) },
  ];
}

/** → [{ file, same, have }] against the files on disk. */
export async function generatedDrift(root = ROOT) {
  const out = [];
  for (const g of await generatedFiles(root)) {
    const have = await readFile(path.join(root, ...g.file.split('/')), 'utf8').catch(() => null);
    out.push({ ...g, have, same: have === g.text });
  }
  return out;
}
