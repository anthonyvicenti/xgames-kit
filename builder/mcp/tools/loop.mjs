// The creation loop's tools, bound to this kit (the factory is builder/mcp/loop-tools.mjs; the library builder/loop/).
// What only this side knows, and nothing more:
//   - places: a `game` argument is a folder under the kit root (games/<name>), or absolute
//   - the state: one sealed store per game (builder/lib/loop-seal.mjs): held in this process's memory once the loop has
//     saved, and checked against its seal by a process that holds nothing (the terminal path, a restarted server)
//   - the seams: builder/loop/kit.mjs (the registry, create, verify, fix, checkpoints)
//   - the play-test's token and report: sealed in the person's config folder (never the game's), the report in the
//     play-tester's own folder (<game>/.gf-loop/job/playtest/out/playtest.json), read only when the token wrote it;
//     the second reader's reading the same way on its own channel (<game>/.gf-loop/job/reader/out/reading.json)
//   - the optional parts (builder/loop/parts.mjs): the economy with web3 on, the backend always (builder/loop/kit.mjs kitParts)
//   - a checkpoint before every round the session works in; gamesfun_rollback restores one
//   - the studio page's roll-back of a run under way: the run is cancelled at the next call (builder/lib/cancel.mjs)
//   - gamesfun_play: the play-tester's hands (and yours, to try a control inside a round)
//   - gamesfun_remove: a round removes a file it made (a scratch file): never one create made, never the loop's folder
