/** The subagent the play-test is handed to (plugin/agents/playtester.md, generated by scripts/gen-loop.mjs). */
export const PLAYTESTER = 'playtester';
/** Tests only: `seams.tools(G)` replaces the kit's tools for a game (a verify with no browser), `seams.registry` the registry, `seams.parts(G)` the parts' adapters. */
export const seams = { tools: null, registry: null, parts: null };

const p = f => toPosix(f);
/** Where a game's loop keeps its things: the play-tester's folder is inside the loop's own, never a game file. */
export function places(arg) {
  if (typeof arg !== 'string' || !arg.trim()) throw new Error('game is required: the game folder, e.g. games/my-game');
  const game = path.resolve(KIT_ROOT, arg);
  if (game === KIT_ROOT || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(path.basename(game))) throw new Error(`${arg}: a game folder is named with letters, digits, dashes and dots, e.g. games/my-game`);
  const playtest = path.join(game, '.gf-loop', 'job', 'playtest'), reader = path.join(game, '.gf-loop', 'job', 'reader');
  return { game, playtest, report: path.join(playtest, 'out', 'playtest.json'), reader, reading: path.join(reader, 'out', 'reading.json'), state: stateFileOf(game) };
}

// one sealed store per game, for as long as this process lives; the session id a call gave; the call under way
const HELD = new Map(), SESSIONS = new Map(), CALLS = new Map();
const storeOf = game => { let s = HELD.get(game); if (!s) HELD.set(game, s = sealedStore(stateFileOf(game), { game })); return s; };
let registry = null;
const registryOf = async () => seams.registry ?? (registry ??= await kitRegistry());

const ending = new AbortController();
let endingHooked = false;
/** A verify under way stops with this process (and with the call, when the session cancels it). */
function stopSignal(ctx) {
  if (!endingHooked) { endingHooked = true; process.once('exit', () => ending.abort()); }
  return ctx?.signal ? AbortSignal.any([ctx.signal, ending.signal]) : ending.signal;
}

/** The sealed one-time tokens and what was handed in with them: the play-tester's report, the second reader's reading. */
const fileOf = (P, channel) => (channel === 'reader' ? { file: P.reading, dir: P.reader, brief: 'READING.md' } : { file: P.report, dir: P.playtest, brief: 'PLAYTEST.md' });
const sealedReports = {
  async issue(G, { message, channel = 'playtest' }) {
    const P = places(G.game), F = fileOf(P, channel), cp = checkpointStore(G.game);
    const name = `${channel}-${await cp.next(channel)}`;
    await cp.keep(name, { step: channel, kind: channel === 'reader' ? 'the files the second reader is given' : 'the files the play-tester is given' });
    await mkdir(path.dirname(F.file), { recursive: true });
    if (existsSync(F.file)) await rename(F.file, `${F.file}.before-${name}`);
    await writeFile(path.join(F.dir, F.brief), String(message));
    return issueToken(G.game, { round: Number(name.split('-')[1]), checkpoint: name, channel });
  },
  current: (G, channel = 'playtest') => currentToken(G.game, { channel }),
  check: (G, token, channel = 'playtest') => tokenProblem(G.game, token, { channel }),
  async keep(G, report, channel = 'playtest') {
    const F = fileOf(places(G.game), channel), text = JSON.stringify(report, null, 2) + '\n';
    await mkdir(path.dirname(F.file), { recursive: true });
    await writeFile(F.file, text);
    await useToken(G.game, text, process.env, { channel });
  },
  async take(G, channel = 'playtest') {
    const F = fileOf(places(G.game), channel), text = await readFile(F.file, 'utf8').catch(() => null);
    if (text == null || !await reportSigned(G.game, text, { channel })) return null;
    await rename(F.file, `${F.file}.read-${Date.now()}`);
    return JSON.parse(text);
  },
};

const bind = {
  registry: null,
  root: KIT_ROOT,
  store: G => storeOf(G.game),
  tools: G => seams.tools?.(G) ?? kitTools({ registry: bind.registry, signal: CALLS.get(G.game)?.signal ?? null, log: m => CALLS.get(G.game)?.log?.(m) }),
  versions: G => kitVersions(G.game),
  gameRef: G => p(G.game),
  reports: sealedReports,
  parts: G => seams.parts?.(G) ?? kitParts(),
  limits: { model: null, strong: 'opus', playtestModel: 'sonnet', readerModel: 'opus' },
  session: (G, id) => { SESSIONS.set(G.game, id); },
  sessionOf: G => SESSIONS.get(G.game) ?? null,
  async handed(G, round) {
    const cp = checkpointStore(G.game);
    await cp.keep(`round-${await cp.next('round')}`, { step: round.step, kind: round.kind + (round.area ? `: ${round.area}` : ''), before: true });
  },
  extra: {
    async next(G) {
      const list = await checkpointStore(G.game).list().catch(() => []);
      return list.length ? { checkpoints: list.map(c => ({ name: c.name, at: c.at, ...(c.meta?.step ? { before: `${c.meta.step}${c.meta.kind ? ` (${c.meta.kind})` : ''}` } : {}) })) } : {};
    },
  },
};
/** The library opened on a game the way the step tools open it (the session's id kept in the state). */
async function openOn(G) {
  return openLoop({ registry: bind.registry, game: G.game, gameRef: p(G.game), store: storeOf(G.game), tools: bind.tools(G), versions: bind.versions(G), limits: bind.limits, parts: bind.parts(G), session: SESSIONS.get(G.game) ?? null });
}

/**
 * What the full verify needs before it starts: a browser, the graphics flags doctor found, and the 3D tools'
 * packages (gate A reads every body's skeleton). Found or installed without writing to stdout (the MCP protocol).
 */
async function readyToVerify(ctx) {
  if (seams.tools) return;
  await ensureBrowser({ log: m => ctx?.log?.(m), install: false });
  Object.assign(process.env, TOOL_ENV, savedGpuEnv());
  if (existsSync(path.join(CHAR_DEPS, 'node_modules'))) return;
  const cli = npmCli();
  if (!cli) throw new Error(`the 3D tools need their npm packages. Run: npm ci --prefix "${CHAR_DEPS}"`);
  ctx?.progress?.('installing the 3D tools\' packages once (gltf-transform, meshoptimizer, sharp)');
  await new Promise((ok, no) => execFile(process.execPath, [cli, 'ci', '--no-audit', '--no-fund'], { cwd: CHAR_DEPS, windowsHide: true, maxBuffer: 32 << 20 }, e => (e ? no(new Error(`npm ci in ${CHAR_DEPS} failed: ${String(e.message).split('\n')[0]}`)) : ok())));
}
const keepAlive = (ctx, words) => { const t0 = Date.now(), t = setInterval(() => ctx?.progress?.(`${words} (${Math.round((Date.now() - t0) / 1000)} s)`), 10000); return () => clearInterval(t); };

/**
 * A roll-back from the studio page while a run is under way CANCELS the run (it never rewinds it: 2026-10-11): the
 * dev server leaves a mark, and the next loop tool ends the run with the library's cancel, puts back files written
 * after the roll-back, and says so. → what the session is told, or null when there is no mark.
 */
async function applyCancel(G) {
  const mark = await readCancel(G.game);
  if (!mark) return null;
  const S = await storeOf(G.game).load();
  let ended = false;
  if (S && S.step !== 'done' && S.status !== 'delivered') ended = !(await (await openOn(G)).cancel(mark.reason)).refused;
  let undone = null;
  const cp = checkpointStore(G.game), kept = mark.checkpoint ? await cp.get(mark.checkpoint) : null;
  if (kept && kept.hash !== await treeHash(G.game)) { const r = await cp.restore(mark.checkpoint); undone = { written: r.written, removed: r.removed }; }
  await clearCancel(G.game);
  return {
    by: 'the person, from the studio page', checkpoint: mark.checkpoint, at: mark.at, runCancelled: ended, ...(undone ? { undoneAgain: undone } : {}),
    do: `The person rolled the game back${mark.label ? ` to "${mark.label}"` : ''}${ended ? ', which ended the run that was under way (cancelled: nothing of it is delivered)' : ''}. The files are as the person left them: do not put the undone changes back. Tell the person, and wait for what they ask next (gamesfun_change).`,
  };
}

/** Every loop tool: the registry loaded, a waiting roll-back applied first (and said), the call's signal and progress kept. */
const bound = t => ({
  ...t,
  async handler(input, ctx) {
    bind.registry ??= await registryOf();
    let told = null, G = null;
    if (typeof input?.game === 'string' && input.game.trim()) { G = places(input.game); told = await applyCancel(G); CALLS.set(G.game, { signal: stopSignal(ctx), log: ctx?.log }); }
    let stop = () => {};
    if (t.name === 'gamesfun_step_verify' && G) { await readyToVerify(ctx); stop = keepAlive(ctx, `verify ${p(G.game)}`); }
    let r;
    try { r = await t.handler(input, ctx); } finally { stop(); if (G) CALLS.delete(G.game); }
    if (!told) return r;
    try { const v = { rolledBack: told, ...JSON.parse(r.content[0].text) }; return { ...r, content: [{ type: 'text', text: JSON.stringify(v, null, 2) }], ...(r.structuredContent ? { structuredContent: v } : {}) }; } catch { return r; }
  },
});

const gameProp = { type: 'string', description: 'The game folder, relative to the kit root (e.g. games/my-game), or absolute.' };

/** gamesfun_play: a new player's hands, black box, in Chrome. Runs go to the play-tester's folder, never the game's files. */
const play = {
  name: 'gamesfun_play',
  annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false },
  outputSchema: PLAY_OUTPUT,
  description: 'Play a game like a new player, black box: scripted real keys and mouse in Chrome, a screenshot of the player\'s own view per step, and the HUD\'s words. The play-tester\'s tool, and yours to try a control before you end a round. Runs go to the loop\'s own folder, so they never change the game\'s files. Steps: start, hold, press, move, look, wait, shot, snap, until, again (builder/tools/lib/play-script.mjs).',
  inputSchema: { type: 'object', required: ['game', 'name', 'steps'], additionalProperties: false, properties: {
    game: gameProp,
    name: { type: 'string', description: 'A short name for this run (letters, digits, dashes), e.g. first-look' },
    steps: { type: 'array', description: 'The step list, e.g. [{"do":"start","bots":3,"seed":1,"round":40},{"do":"hold","key":"Mouse","seconds":2,"shot":"firing"}]. Always starts with a start step.' },
  } },
  async handler({ game, name, steps }, ctx) {
    const P = places(game);
    if (!isGame(P.game)) throw new Error(`${game}: not a game folder yet`);
    if (!/^[a-z0-9][a-z0-9-]{0,40}$/.test(name)) throw new Error('name: lowercase letters, digits and dashes');
    const script = path.join(P.playtest, 'scratch', `${name}.json`), out = path.join(P.playtest, 'runs', name);
    await mkdir(path.dirname(script), { recursive: true });
    await writeFile(script, JSON.stringify(steps, null, 1) + '\n');
    const stop = keepAlive(ctx, `play ${name}`);
    let r;
    try { r = await ctx.runCli(['play', P.game, '--script', script, '--out', out]); } finally { stop(); }
    const shots = (await readdir(out).catch(() => [])).filter(f => /\.(jpe?g|png)$/i.test(f)).sort().map(f => p(path.join(out, f)));
    const log = r.stdout.trim().split('\n').slice(-80);
    if (r.code !== 0 && !shots.length) throw new Error(`play did not run (exit ${r.code}): ${(r.stderr || r.stdout).trim().split('\n').slice(-4).join(' | ')}`);
    return { run: name, folder: p(out), evidenceBase: p(P.playtest), screenshots: shots, log, ...(r.code ? { exit: r.code, errors: r.stderr.trim().split('\n').slice(-4) } : {}), note: 'Open the screenshots (read the image files) before you judge anything.' };
  },
};

/** gamesfun_rollback: a checkpoint back, byte for byte; the loop's state is not rewound (proof on the undone files is stale). */
const rollback = {
  name: 'gamesfun_rollback',
  annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: true, openWorldHint: false },
  outputSchema: ROLLBACK_OUTPUT,
  description: 'Undo a round: restores the game folder to the checkpoint taken before that round (every file put back, files the round added removed), byte for byte. Default: the latest round. The loop\'s state is not rewound: proof recorded on the undone files is now stale, and the next tool says what to run. gamesfun_next lists the checkpoints.',
  inputSchema: { type: 'object', required: ['game'], additionalProperties: false, properties: { game: gameProp, round: { type: 'integer', description: 'The round number (the checkpoint round-<n>). Default: the latest.' }, checkpoint: { type: 'string', description: 'A checkpoint by name instead, e.g. playtest-1, created, verified.' } } },
  async handler({ game, round, checkpoint }) {
    const P = places(game), cp = checkpointStore(P.game), list = await cp.list();
    const name = checkpoint ?? `round-${round ?? await cp.next('round') - 1}`;
    if (!list.some(c => c.name === name)) return { isError: true, content: [{ type: 'text', text: JSON.stringify({ refused: 'no-checkpoint', why: `No checkpoint "${name}" for ${p(P.game)}.`, checkpoints: list.map(c => c.name) }, null, 2) }] };
    const r = await cp.restore(name);
    const S = await storeOf(P.game).load(), w = where(S, game);
    return {
      game: p(P.game), restored: name, takenAt: r.at, written: r.written, removed: r.removed, hash: r.hash,
      ...(S?.lock ? { proof: proofOf(S, await bind.tools({ game: P.game }).hash(P.game)) } : {}),
      note: 'The files are what they were at that checkpoint. The loop\'s state is unchanged: a verify or play-test recorded on the undone files is stale and runs again before delivery.',
      next: w.tool ? { tool: w.tool, args: w.args } : w.after ?? null,
    };
  },
};

/** gamesfun_remove: a round's own leftovers, gone; what create made (the game's own files, the kit's copies) stays. */
const remove = {
  name: 'gamesfun_remove',
  annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: true, openWorldHint: false },
  outputSchema: { type: 'object', required: ['removed', 'refused'], properties: { removed: { type: 'array', items: { type: 'string' } }, refused: { type: 'array', items: { type: 'object' } } } },
  description: 'Remove files you made in the game and no longer need (a scratch file, a module you replaced), by their paths in the game folder. Only a file that was not there when create made the game: a file create made (the game\'s own rules.js, config, a kit copy) is changed, never removed; the loop\'s own folder and links are never touched. Each refused path says why.',
  inputSchema: { type: 'object', required: ['game', 'paths'], additionalProperties: false, properties: { game: gameProp, paths: { type: 'array', minItems: 1, maxItems: 50, items: { type: 'string' }, description: 'Paths relative to the game folder, e.g. ["rules.js.new", "src/old-board.js"].' } } },
  async handler({ game, paths }) {
    const P = places(game);
    if (!isGame(P.game)) throw new Error(`${game}: not a game folder yet`);
    return { game: p(P.game), ...(await removeMade(P.game, paths)) };
  },
};

export const tools = [...loopTools(bind).map(bound), play, rollback, remove];
