#!/usr/bin/env node
// Writes runtimes/vista/kit/core-files.js: every model, picture and data file the vista core reads from its public
// folder (core/public/models, core/public/textures), each with the slot it is in a game (kit/config.js coreSlots) and
// the core module that draws it (kit/coverage.js tags what that module adds to the scene). The core's sounds are not
// here: they are the game's sound list already (assets.json → sounds, kit/audio.js).
//
//   node runtimes/vista/tools/core-files.mjs           (re)write kit/core-files.js
//   node runtimes/vista/tools/core-files.mjs --check   exit 1 when kit/core-files.js is not the core's files (a test runs it)
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { join, dirname, resolve, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const VISTA = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(VISTA, 'core/public');
const OUT = join(VISTA, 'kit/core-files.js');
const TYPE = { '.glb': 'model', '.png': 'image', '.jpg': 'image', '.jpeg': 'image', '.json': 'data' };
/** The core module that reads each folder (core/src): what kit/coverage.js tags with the folder's slots. */
const BY = { 'models/props': 'game/StallKit.js', 'models/debris': 'world/debris/ScannedDebris.js', 'models/whale': 'world/marine/Whale.js', 'models/characters': 'engine/loaders/GLTF.js', 'textures/smaa': 'post/AntiAlias.js' };
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

async function walk(dir, rel = '') {
  const out = [];
  for (const e of await readdir(join(dir, rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...await walk(dir, r)); else out.push(r);
  }
  return out;
}

export async function coreFiles() {
  const files = [];
  for (const top of ['models', 'textures']) for (const rel of (await walk(PUBLIC, top)).sort()) {
    const type = TYPE[extname(rel).toLowerCase()];
    if (!type) continue;    // licences and credits travel beside the files; humpback.bin goes with humpback.json
    const folder = dirname(rel), name = basename(rel, extname(rel));
    files.push({ file: rel, slot: `core.${slug(folder.replace(/^models\//, ''))}.${slug(name)}`.slice(0, 80), type, by: BY[folder] ?? null, bytes: (await stat(join(PUBLIC, rel))).size });
  }
  return files;
}

const render = files => `// Generated by runtimes/vista/tools/core-files.mjs: every model, picture and data file the vista core reads from its
// public folder, the slot it is in a game and the core module that draws it. Do not edit by hand.
export const CORE_FILES = ${JSON.stringify(files, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const text = render(await coreFiles());
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have !== text) { console.error('kit/core-files.js is not the core\'s files: run node runtimes/vista/tools/core-files.mjs'); process.exitCode = 1; }
    else console.log('kit/core-files.js is current');
  } else { await writeFile(OUT, text); console.log(`kit/core-files.js: ${(await coreFiles()).length} files`); }
}
